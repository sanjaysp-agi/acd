"""Generates a reviewer-facing Section 16.3 report as a .docx: one heading
+ table per topic, numerical figures and validation status only -- no
narrative/clinical text is generated, same restriction the other generators
in this package (report_generator.py, audit_generator.py) already honor."""
from __future__ import annotations

from pathlib import Path

import docx
from docx.shared import Pt

from generation.formatting import format_case_ratio
from models.schemas import MetricResult


def _cell_text(value) -> str:
    if value is None:
        return "-"
    if isinstance(value, dict):
        return "; ".join(f"{k}={v}" for k, v in value.items())
    if isinstance(value, list):
        return "; ".join(str(v) for v in value[:10])
    return str(value)


def generate_docx_report(metric_results: list[MetricResult], output_path: str | Path) -> str:
    by_topic: dict[str, dict] = {}
    for mr in metric_results:
        key = mr.pbrer_section_number or "Total"
        entry = by_topic.setdefault(key, {"heading": mr.topic_heading, "rows": []})
        entry["rows"].append(mr)

    document = docx.Document()
    document.add_heading("Section 16.3 -- New Information on Important Identified Risks", level=1)
    document.add_paragraph(
        "Numerical figures generated by the PBRER Section 16.3 Automation pipeline. "
        "Each value is traceable to its source workbook and calculation method -- see the "
        "accompanying audit package for full evidence."
    )

    for section in sorted(by_topic):
        entry = by_topic[section]
        document.add_heading(f"{section} -- {entry['heading']}", level=2)

        table = document.add_table(rows=1, cols=4)
        table.style = "Light Grid Accent 1"
        header_cells = table.rows[0].cells
        for cell, text in zip(header_cells, ["Metric", "Value", "Historical", "Status"]):
            cell.text = text
            cell.paragraphs[0].runs[0].font.bold = True
            cell.paragraphs[0].runs[0].font.size = Pt(10)

        # metric_id -> calculated_value for this topic only, so
        # serious_case_count/fatal_case_count rows can look up their
        # sibling topic_case_count/total_case_count denominator -- see
        # generation.formatting.format_case_ratio.
        topic_metrics = {row.metric_id: row.calculated_value for row in entry["rows"]}

        for mr in entry["rows"]:
            row_cells = table.add_row().cells
            row_cells[0].text = mr.metric_id
            row_cells[1].text = _cell_text(format_case_ratio(mr.metric_id, mr.calculated_value, topic_metrics))
            row_cells[2].text = _cell_text(mr.historical_value)
            row_cells[3].text = mr.validation_status

        document.add_paragraph()

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    document.save(output_path)
    return str(output_path)
